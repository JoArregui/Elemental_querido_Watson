  @override
  Future<PuzzleModel> getPuzzle(String id) async {
    await Future.delayed(const Duration(milliseconds: 300));
    return _puzzlesList.firstWhere(
      (p) => p.id == id,
      orElse: () => _puzzlesList.first,
    );
  }

  @override
  Future<List<PuzzleModel>> getAllPuzzles() async {
    await Future.delayed(const Duration(milliseconds: 300));
    return _puzzlesList;
  }
